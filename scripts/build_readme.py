"""Rebuild README.md: newest public repo on top, the rest in the sections from profile.json.

Run: GITHUB_TOKEN=... python3 scripts/build_readme.py
"""
import base64, json, os, re, sys, urllib.request

API = "https://api.github.com"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def get(path):
    req = urllib.request.Request(API + path, headers={"Accept": "application/vnd.github+json"})
    if os.environ.get("GITHUB_TOKEN"):
        req.add_header("Authorization", "Bearer " + os.environ["GITHUB_TOKEN"])
    try:
        with urllib.request.urlopen(req) as r:
            return json.load(r)
    except urllib.error.HTTPError as e:
        if e.code == 404:
            return None
        raise


def file_text(owner, repo, name):
    data = get(f"/repos/{owner}/{repo}/contents/{name}")
    return base64.b64decode(data["content"]).decode("utf-8", "replace") if data else ""


def blurb(desc):
    """Short line: the part before ': ' or ' — ' when that part is long enough."""
    desc = (desc or "").strip()
    for sep in (": ", " — "):
        head = desc.split(sep, 1)[0]
        if sep in desc and len(head) >= 20:
            desc = head
    return desc.rstrip(".") + "." if desc else ""


def first_image(readme, owner, repo, branch):
    m = re.search(r"!\[[^\]]*\]\(([^)\s]+)", readme) or re.search(r'<img[^>]+src="([^"]+)"', readme)
    if not m:
        return None
    src = m.group(1)
    if src.startswith("http"):
        return src
    return f"https://raw.githubusercontent.com/{owner}/{repo}/{branch}/{src.lstrip('./')}"


def version(changelog):
    m = re.search(r"^##\s*\[?v?(\d+\.\d+\.\d+)", changelog, re.M)
    return m.group(1) if m else None


def info(owner, r):
    name, branch = r["name"], r["default_branch"]
    readme = file_text(owner, name, "README.md")
    return {
        "name": name,
        "url": r["html_url"],
        "blurb": blurb(r["description"]),
        "img": first_image(readme, owner, name, branch),
        "install": r["html_url"] + ("#install" if re.search(r"^#+\s*Install", readme, re.M) else ""),
        "version": version(file_text(owner, name, "CHANGELOG.md")),
    }


def card(s):
    img = f'<a href="{s["url"]}"><img src="{s["img"]}" alt="{s["name"]}"></a><br>' if s["img"] else ""
    return (f'<td width="33%" valign="top">\n{img}\n<h3><a href="{s["url"]}">{s["name"]}</a></h3>\n'
            f'<p>{s["blurb"]}</p>\n<p><a href="{s["install"]}"><strong>Install →</strong></a></p>\n</td>')


def grid(items):
    rows = [items[i:i + 3] for i in range(0, len(items), 3)]
    body = "".join("<tr>\n" + "\n".join(card(s) for s in row) + "\n</tr>\n" for row in rows)
    return f"<table>\n{body}</table>\n"


def build(cfg, repos):
    owner = cfg["owner"]
    public = [r for r in repos
              if not r["private"] and not r["fork"] and not r["archived"]
              and r["name"] not in cfg["exclude"] and cfg["hide_topic"] not in r.get("topics", [])]
    public.sort(key=lambda r: r["created_at"], reverse=True)
    if not public:
        sys.exit("no public repos found")
    newest = info(owner, public[0])
    by_name = {r["name"]: r for r in public[1:]}

    badges = f'<code>{newest["version"]}</code> &nbsp;' if newest["version"] else ""
    img = f'<a href="{newest["url"]}"><img src="{newest["img"]}" alt="{newest["name"]}" width="100%"></a>' if newest["img"] else ""
    out = [
        "<!-- Generated by scripts/build_readme.py. Edit profile.json or the script, not this file. -->",
        "",
        "![WorkSpace Labs. Agent skills that show their work. For Claude Code and Codex: the agent does the work, a human decides.](media/profile-hero.png)",
        "",
        '<p align="center">',
        '<a href="https://workspace-labs.net"><strong>Website ↗</strong></a> &nbsp;·&nbsp;',
        '<a href="https://www.linkedin.com/in/workspacelabs"><strong>LinkedIn</strong></a> &nbsp;·&nbsp;',
        '<a href="https://x.com/workspacelabs91"><strong>X</strong></a>',
        "</p>",
        "",
        "## ✨ Newest",
        "",
        "<table>\n<tr>",
        f'<td width="55%">{img}</td>',
        f'<td valign="middle">\n{badges}🆕\n<h3><a href="{newest["url"]}">{newest["name"]}</a></h3>\n'
        f'<p>{newest["blurb"]}</p>\n<p><a href="{newest["install"]}"><strong>Install →</strong></a></p>\n</td>',
        "</tr>\n</table>",
        "",
    ]
    for sec in cfg["sections"]:
        items = [info(owner, by_name.pop(n)) for n in sec["repos"] if n in by_name]
        if items:
            out += [f"## {sec['title']}", "", grid(items)]
    if by_name:  # public repos not placed in a section yet
        out += [f"## {cfg['more_title']}", "", grid([info(owner, r) for r in by_name.values()])]
    out += ['<p align="center"><a href="https://github.com/workspace-labs?tab=repositories">'
            "<strong>All repositories →</strong></a></p>", ""]
    return "\n".join(out)


def main():
    cfg = json.load(open(os.path.join(ROOT, "profile.json")))
    repos = get(f"/users/{cfg['owner']}/repos?per_page=100&type=owner")
    with open(os.path.join(ROOT, "README.md"), "w") as f:
        f.write(build(cfg, repos))


if __name__ == "__main__":
    main()
